"""
The sample hospital's wordmark (infra/hospitals/hsp-musterstadt/logo.svg and logo-on-dark.svg), generated.

The panel shows the logo as an <img>, which is its own document: it cannot use the page's web font, so an SVG with a
<text> element renders in whatever fallback the viewer has — a different width on every platform, and a viewBox sized
for one of them leaves a gap or clips on the others. The wordmark is therefore set in the panel's own typeface (Geist,
self-hosted in med_app via @fontsource-variable) and the glyphs are written as paths, so it looks the same everywhere
and the viewBox fits it exactly.

    python docs/media/scripts/wordmark.py            # needs fonttools, brotli, uharfbuzz (pip) and med_app/node_modules

A real hospital replaces the two files with its own logo; see README "Customise the branding".
"""

from __future__ import annotations

import io
import sys
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[3]
FONT = ROOT / "med_app" / "node_modules" / "@fontsource-variable" / "geist" / "files" / "geist-latin-wght-normal.woff2"
OUT = ROOT / "infra" / "hospitals" / "hsp-musterstadt"

SIZE = 20          # px, in a 40-high box — the panel scales the whole mark to 28px
BASELINE = 27
TEXT_X = 52        # after the 40px icon and a 12px gap
TRACKING = -0.2    # px, as the original <text> had
RUNS = (("Klinikum ", 600), ("Musterstadt", 400))
ACCENT, INK = "#1F4E9E", "#16213A"


def instance(weight: int) -> TTFont:
    font = TTFont(str(FONT))
    font.flavor = None  # work on the decompressed sfnt
    return instantiateVariableFont(font, {"wght": weight}, inplace=False)


def run_paths(text: str, weight: int, x: float) -> tuple[str, float]:
    """SVG path data for `text` set at `x`, and the pen position after it (HarfBuzz-shaped, so kerning applies)."""
    font = instance(weight)
    buf = io.BytesIO()
    font.save(buf)
    face = hb.Face(buf.getvalue())
    hbfont = hb.Font(face)
    upem = face.upem
    hbfont.scale = (upem, upem)
    hb.ot_font_set_funcs(hbfont)
    b = hb.Buffer()
    b.add_str(text)
    b.guess_segment_properties()
    hb.shape(hbfont, b, {"kern": True, "liga": True})
    scale = SIZE / upem
    glyph_order = font.getGlyphOrder()
    glyph_set = font.getGlyphSet()
    paths: list[str] = []
    for info, pos in zip(b.glyph_infos, b.glyph_positions):
        name = glyph_order[info.codepoint]
        pen = SVGPathPen(glyph_set, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
        # font units → px: scale, flip y, move to the pen position on the baseline
        glyph_set[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x + pos.x_offset * scale, BASELINE - pos.y_offset * scale)))
        d = pen.getCommands()
        if d:
            paths.append(d)
        x += pos.x_advance * scale + TRACKING
    return " ".join(paths), x


def wordmark(fill: str, label: str) -> str:
    x = float(TEXT_X)
    text_paths: list[str] = []
    for text, weight in RUNS:
        d, x = run_paths(text, weight, x)
        text_paths.append(d)
    width = round(x - TRACKING + 2)  # the last advance, without trailing tracking, plus a hair of air
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} 40" width="{width}" height="40" role="img" aria-label="{label}">
  <!-- Sample wordmark for the invented Klinikum Musterstadt, generated by docs/media/scripts/wordmark.py: the name is set in
       Geist (the panel's typeface) and outlined, so it renders the same everywhere and the box fits it. Replace this file
       (and logo-on-dark.svg) with your hospital's logo; keep the names, or change `branding.logo.src` / `srcOnDark` in
       hospitals/hsp-musterstadt.json to match. -->
  <rect x="0" y="0" width="40" height="40" rx="9" fill="{ACCENT}"/>
  <path d="M15 11h10v4h-10zM15 25h10v4h-10zM18 11h4v18h-4z" fill="#FFFFFF"/>
  <path fill="{fill}" d="{' '.join(text_paths)}"/>
</svg>
"""


if __name__ == "__main__":
    if not FONT.exists():
        sys.exit(f"{FONT} not found — run `npm install` in med_app first")
    (OUT / "logo.svg").write_text(wordmark(INK, "Klinikum Musterstadt"), encoding="utf-8")
    (OUT / "logo-on-dark.svg").write_text(wordmark("#FFFFFF", "Klinikum Musterstadt (on dark)"), encoding="utf-8")
    print("wrote", OUT / "logo.svg", "and logo-on-dark.svg")
