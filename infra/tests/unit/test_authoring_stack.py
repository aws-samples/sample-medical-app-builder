def test_the_agent_and_the_drafts_api_read_the_record_shape_library_from_the_registry_and_nothing_writes_it_but_the_writer(synthesized):
    template, _ = synthesized
    functions = {f["Properties"].get("FunctionName"): f for f in template.find_resources("AWS::Lambda::Function").values()}
    roles = template.find_resources("AWS::IAM::Role")

    def managed(fn_name: str) -> str:
        return json.dumps(roles[functions[fn_name]["Properties"]["Role"]["Fn::GetAtt"][0]]["Properties"].get("ManagedPolicyArns", []))

    for name in ("medapp-hsp-test-drafting-agent", "medapp-hsp-test-drafts-api"):
        assert "REGISTRY_TABLE_NAME" in functions[name]["Properties"]["Environment"]["Variables"], name
        assert "RegistryRead" in managed(name) and "Writer" not in managed(name), f"{name} reads the library and cannot write the registry"
    assert "Writer" in managed("medapp-hsp-test-registry-write") and "RegistryRead" not in managed("medapp-hsp-test-registry-write")
    assert "REGISTRY_TABLE_NAME" not in functions["medapp-hsp-test-manifest-service"]["Properties"]["Environment"]["Variables"], "the compiler is handed the artifacts; it does not read the table"
