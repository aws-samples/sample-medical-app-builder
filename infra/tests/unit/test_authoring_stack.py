def test_the_record_vocabulary_bucket_is_private_versioned_and_read_only_for_the_agent(synthesized):
    template, stack = synthesized
    assert stack.vocabulary_key == "record-vocabulary.json"
    buckets = {name: b for name, b in template.find_resources("AWS::S3::Bucket").items() if "RecordVocabulary" in name}
    assert len(buckets) == 1
    (bucket,) = buckets.values()
    props = bucket["Properties"]
    assert props["PublicAccessBlockConfiguration"]["BlockPublicPolicy"] is True and props["VersioningConfiguration"] == {"Status": "Enabled"}
    assert props["BucketEncryption"]["ServerSideEncryptionConfiguration"][0]["ServerSideEncryptionByDefault"]["SSEAlgorithm"] == "AES256"
    assert props["LifecycleConfiguration"]["Rules"][0]["NoncurrentVersionExpiration"] == {"NoncurrentDays": 30}, "old versions kept a month for a rollback by hand"
    assert bucket["DeletionPolicy"] == "Delete", "regenerated by the next seed run; nothing to retain"

    functions = {f["Properties"].get("FunctionName"): f for f in template.find_resources("AWS::Lambda::Function").values()}
    agent_env = functions["medapp-hsp-test-drafting-agent"]["Properties"]["Environment"]["Variables"]
    assert agent_env["RECORD_VOCABULARY_KEY"] == "record-vocabulary.json" and "RecordVocabulary" in json.dumps(agent_env["RECORD_VOCABULARY_BUCKET"])
    assert agent_env["MEDAPP_CATALOG_DIR"] == "/var/task/data" and agent_env["MODEL_ID"] == "eu.anthropic.claude-sonnet-5-5"
    for other in ("medapp-hsp-test-drafts-api", "medapp-hsp-test-registry-write", "medapp-hsp-test-manifest-service"):
        assert "RECORD_VOCABULARY_BUCKET" not in functions[other]["Properties"]["Environment"]["Variables"], f"{other} does not read it"

    # The agent reads; it never writes — the data source's seed does (granted in that stack).
    statements = [s for p in template.find_resources("AWS::IAM::Policy").values() for s in p["Properties"]["PolicyDocument"]["Statement"] if "RecordVocabulary" in json.dumps(s.get("Resource"))]
    actions = sorted({a for s in statements for a in (s["Action"] if isinstance(s["Action"], list) else [s["Action"]])})
    assert any(a.startswith("s3:GetObject") for a in actions) and not any(a.startswith(("s3:Put", "s3:Delete")) for a in actions)
    roles = {json.dumps(p["Properties"]["Roles"]) for p in template.find_resources("AWS::IAM::Policy").values() if "RecordVocabulary" in json.dumps(p["Properties"]["PolicyDocument"]) and "s3:GetObject" in json.dumps(p["Properties"]["PolicyDocument"])}
    assert len(roles) == 1 and "DraftingAgentFn" in next(iter(roles))

    template.has_resource_properties("AWS::SSM::Parameter", {"Name": "/medapp/hsp-test/authoring/vocabulary-bucket"})
    template.has_output("RecordVocabularyUri", {"Value": Match.object_like({"Fn::Join": Match.any_value()})})


def test_the_agent_may_only_invoke_models_inside_the_geography(synthesized):
    # Data residency, twice: app.py refuses a model id outside the geography at synth, and the agent's role cannot reach
    # one even if the id changed — a cross-region profile needs the model in each destination region, all of them eu-*.
    template, _ = synthesized
    statements = [s for p in template.find_resources("AWS::IAM::Policy").values() for s in p["Properties"]["PolicyDocument"]["Statement"] if s.get("Sid") == "Bedrock"]
    assert len(statements) == 1
    resources = json.dumps(statements[0]["Resource"])
    assert "arn:aws:bedrock:eu-*::foundation-model/*" in resources and "arn:aws:bedrock:eu-*:" in resources
    assert "arn:aws:bedrock:*" not in resources, "no region wildcard outside the geography"


def test_publishing_may_find_the_data_sources_definitions_writer_and_invoke_it_and_nothing_wider(synthesized):
    """An app's own forms go to the record at publish: the registry write Lambda reads one SSM parameter and may invoke the deployment's seed Lambdas — no construct reference, so no dependency on the servers' stacks."""
    template, _ = synthesized
    functions = {f["Properties"].get("FunctionName"): f for f in template.find_resources("AWS::Lambda::Function").values()}
    env = functions["medapp-hsp-test-registry-write"]["Properties"]["Environment"]["Variables"]
    assert env["DEFINITIONS_WRITER_PARAMETER"] == "/medapp/hsp-test/data-source/definitions-writer"
    statements = [st for p in template.find_resources("AWS::IAM::Policy").values() for st in p["Properties"]["PolicyDocument"]["Statement"]]
    lookup = next(st for st in statements if st.get("Sid") == "DefinitionsWriterLookup")
    assert lookup["Action"] == "ssm:GetParameter" and "parameter/medapp/hsp-test/data-source/definitions-writer" in json.dumps(lookup["Resource"])
    invoke = next(st for st in statements if st.get("Sid") == "DefinitionsWriterInvoke")
    assert invoke["Action"] == "lambda:InvokeFunction" and "function:medapp-hsp-test-*-seed" in json.dumps(invoke["Resource"])


