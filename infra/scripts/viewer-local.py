#!/usr/bin/env python3
"""
The imaging viewer on your laptop, against a PACS made of the generated seed — no AWS involved.

    scripts/viewer-local.py                  # serves OHIF (the staged build) and a DICOMweb server over .build/dicom-seed; prints the URLs
    scripts/viewer-local.py --check          # additionally drives headless Chromium through a study and reports console errors
    scripts/viewer-local.py --check --study 1.2.276.0.7230010.3.1.2.8323329.1002 --screenshot /tmp/viewer.png

Two local servers: the OHIF build (`stage_ohif()`, the same files the ViewerStack uploads) with an app-config.js
generated by the same function the stack uses (`ohif_app_config`), pointing at a minimal DICOMweb server (QIDO-RS
studies/series/instances, WADO-RS metadata and frames, CORS) that reads the DICOM files `seeding/dicom_seed.py`
generated. Requests must carry `Authorization: Bearer …` like the real door (the token comes from the URL fragment
the same way the panel hands it over). `--check` needs `pip install playwright && python -m playwright install chromium`.
"""

