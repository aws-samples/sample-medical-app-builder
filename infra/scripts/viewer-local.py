BOUNDARY = "medapp-frame-boundary"


class FakePacs:
    """DICOMweb over a folder of DICOM files: enough QIDO-RS/WADO-RS for OHIF to open a study."""

    def __init__(self, folder: Path) -> None:
        import pydicom

        self.instances: dict[str, tuple[Path, object]] = {}  # sop uid → (path, header dataset)
        self.by_series: dict[str, list[str]] = {}
        self.by_study: dict[str, list[str]] = {}
        self.requests: list[dict] = []
        for path in sorted(folder.rglob("*.dcm")):
            ds = pydicom.dcmread(path, stop_before_pixels=True)
            sop = str(ds.SOPInstanceUID)
            self.instances[sop] = (path, ds)
            self.by_series.setdefault(str(ds.SeriesInstanceUID), []).append(sop)
            self.by_study.setdefault(str(ds.StudyInstanceUID), []).append(sop)

    def _first(self, sops: list[str]):
        return self.instances[sops[0]][1]

    def study_json(self, study_uid: str) -> dict:
        ds = self._first(self.by_study[study_uid])
        series = {str(self.instances[s][1].SeriesInstanceUID) for s in self.by_study[study_uid]}
        modalities = sorted({str(self.instances[s][1].Modality) for s in self.by_study[study_uid]})
        return {
            "0020000D": {"vr": "UI", "Value": [study_uid]},
            "00080020": {"vr": "DA", "Value": [str(ds.StudyDate)]},
            "00080030": {"vr": "TM", "Value": [str(ds.StudyTime)]},
            "00080050": {"vr": "SH", "Value": [str(ds.AccessionNumber)]},
            "00080061": {"vr": "CS", "Value": modalities},
            "00081030": {"vr": "LO", "Value": [str(ds.StudyDescription)]},
            "00100010": {"vr": "PN", "Value": [{"Alphabetic": str(ds.PatientName)}]},
            "00100020": {"vr": "LO", "Value": [str(ds.PatientID)]},
            "00201206": {"vr": "IS", "Value": [len(series)]},
            "00201208": {"vr": "IS", "Value": [len(self.by_study[study_uid])]},
        }

    def series_json(self, series_uid: str) -> dict:
        ds = self._first(self.by_series[series_uid])
        return {
            "0020000D": {"vr": "UI", "Value": [str(ds.StudyInstanceUID)]},
            "0020000E": {"vr": "UI", "Value": [series_uid]},
            "00080060": {"vr": "CS", "Value": [str(ds.Modality)]},
            "0008103E": {"vr": "LO", "Value": [str(ds.SeriesDescription)]},
            "00200011": {"vr": "IS", "Value": [int(ds.SeriesNumber)]},
            "00201209": {"vr": "IS", "Value": [len(self.by_series[series_uid])]},
        }

    def instance_json(self, sop: str, base: str) -> dict:
        import pydicom

        path, _ = self.instances[sop]
        ds = pydicom.dcmread(path)
        study, series = str(ds.StudyInstanceUID), str(ds.SeriesInstanceUID)

        def bulk(element):
            return f"{base}/studies/{study}/series/{series}/instances/{sop}/bulk/{element.tag.group:04X}{element.tag.element:04X}"

        return ds.to_json_dict(bulk_data_threshold=1024, bulk_data_element_handler=bulk)

    def frame(self, sop: str) -> bytes:
        import pydicom

        path, _ = self.instances[sop]
        return bytes(pydicom.dcmread(path).PixelData)


def pacs_server(pacs: FakePacs, port: int) -> ThreadingHTTPServer:
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *_args):
            pass

        def _cors(self):
            self.send_header("Access-Control-Allow-Origin", "*")
            self.send_header("Access-Control-Allow-Headers", "authorization, content-type, accept, x-requested-with")
            self.send_header("Access-Control-Allow-Methods", "GET, OPTIONS")

        def _reply(self, status: int, body: bytes = b"", content_type: str = "application/dicom+json"):
            self.send_response(status)
            self._cors()
            if body:
                self.send_header("Content-Type", content_type)
                self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            if body:
                self.wfile.write(body)

        def do_OPTIONS(self):
            self._reply(204)

        def do_GET(self):
            parsed = urllib.parse.urlparse(self.path)
            params = urllib.parse.parse_qs(parsed.query)
            pacs.requests.append({"path": parsed.path, "query": parsed.query, "authorization": self.headers.get("authorization"), "accept": self.headers.get("accept")})
            if not self.headers.get("authorization", "").startswith("Bearer "):
                return self._reply(401, b'{"message":"Unauthorized"}', "application/json")
            base = f"http://{self.headers['host']}/dicom-web"
            parts = [p for p in parsed.path.split("/") if p][1:]  # after 'dicom-web'
            try:
                if parts == ["studies"]:
                    uids = params.get("StudyInstanceUID") or params.get("0020000D")
                    patient = (params.get("PatientID") or params.get("00100020") or [None])[0]  # keyword or tag, as QIDO allows
                    studies = [u for u in pacs.by_study if (not uids or u in uids) and (not patient or str(pacs._first(pacs.by_study[u]).PatientID) == patient)]
                    return self._reply(200, json.dumps([pacs.study_json(u) for u in studies]).encode()) if studies else self._reply(204)
                if len(parts) == 3 and parts[2] == "series":
                    series = sorted({str(pacs.instances[s][1].SeriesInstanceUID) for s in pacs.by_study[parts[1]]})
                    return self._reply(200, json.dumps([pacs.series_json(s) for s in series]).encode())
                if len(parts) == 3 and parts[2] == "metadata":
                    return self._reply(200, json.dumps([pacs.instance_json(s, base) for s in pacs.by_study[parts[1]]]).encode())
                if len(parts) == 5 and parts[4] == "metadata":
                    return self._reply(200, json.dumps([pacs.instance_json(s, base) for s in pacs.by_series[parts[3]]]).encode())
                if len(parts) == 5 and parts[4] == "instances":
                    return self._reply(200, json.dumps([{k: v for k, v in pacs.instance_json(s, base).items() if k in ("00080016", "00080018", "0020000D", "0020000E", "00200013", "00280008")} for s in pacs.by_series[parts[3]]]).encode())
                if len(parts) == 7 and parts[6] == "metadata":
                    return self._reply(200, json.dumps([pacs.instance_json(parts[5], base)]).encode())
                if len(parts) == 8 and parts[6] == "frames":
                    pixels = pacs.frame(parts[5])
                    body = (f"--{BOUNDARY}\r\nContent-Type: application/octet-stream\r\nContent-Length: {len(pixels)}\r\n\r\n").encode() + pixels + f"\r\n--{BOUNDARY}--\r\n".encode()
                    return self._reply(200, body, f'multipart/related; type="application/octet-stream"; boundary={BOUNDARY}')
            except KeyError:
                return self._reply(404, b'{"message":"not found"}', "application/json")
            return self._reply(404, json.dumps({"message": f"no route for {parsed.path}"}).encode(), "application/json")

    return ThreadingHTTPServer(("127.0.0.1", port), Handler)


def viewer_server(dist: Path, app_config: str, port: int) -> ThreadingHTTPServer:
    mimetypes.add_type("application/wasm", ".wasm")
    mimetypes.add_type("application/javascript", ".js")

    class Handler(SimpleHTTPRequestHandler):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, directory=str(dist), **kwargs)

        def log_message(self, *_args):
            pass

        def do_GET(self):
            path = urllib.parse.urlparse(self.path).path
            if path == f"/{APP_CONFIG_KEY}":
                body = app_config.encode()
                self.send_response(200)
                self.send_header("Content-Type", "application/javascript")
                self.send_header("Content-Length", str(len(body)))
                self.send_header("Cache-Control", "no-cache")
                self.end_headers()
                self.wfile.write(body)
                return
            if not (dist / path.lstrip("/")).is_file():  # SPA routes → index.html, as CloudFront does
                self.path = "/index.html"
            super().do_GET()

    return ThreadingHTTPServer(("127.0.0.1", port), Handler)


# A camera that can still draw: finite, not vtk's untouched default (position 0,0,1 looking at the origin — what a
# NaN camera reads back as), and view-up not parallel to the view direction.
CAMERAS_JS = """() => {
  const engine = window.services && window.services.cornerstoneViewportService.getRenderingEngine();
  if (!engine) return [];
  return engine.getViewports().map(vp => {
    const c = vp.getCamera();
    const finite = [...c.position, ...c.focalPoint, ...c.viewUp, ...c.viewPlaneNormal].every(Number.isFinite);
    const untouched = c.position.join() === '0,0,1' && c.focalPoint.join() === '0,0,0';
    const dot = Math.abs(c.viewUp[0] * c.viewPlaneNormal[0] + c.viewUp[1] * c.viewPlaneNormal[1] + c.viewUp[2] * c.viewPlaneNormal[2]);
    return { id: vp.id, orientation: vp.viewportProperties && vp.viewportProperties.orientation, usable: finite && !untouched && dot < 0.99 };
  });
}"""


def check(viewer_url: str, study_uid: str, token: str, pacs: FakePacs, screenshot: str | None, timeout_s: float, hanging_protocol: str | None = None, settle_s: float = 2.0, series_uid: str | None = None, whole_series: bool = False, orientation_change: str | None = None) -> int:
    from playwright.sync_api import sync_playwright

    errors: list[str] = []
    warnings: list[str] = []
    failed: list[str] = []
    cameras: list[dict] = []
    warnings_after_change: list[str] = []
    with sync_playwright() as p:
        browser = p.chromium.launch(args=["--use-gl=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"])
        page = browser.new_page(viewport={"width": 1280, "height": 800})
        page.on("console", lambda m: errors.append(m.text) if m.type == "error" else warnings.append(m.text) if m.type == "warning" else None)
        page.on("pageerror", lambda e: errors.append(f"pageerror: {e}"))
        page.on("requestfailed", lambda r: failed.append(f"{r.url} {r.failure}"))
        protocol = f"&hangingProtocolId={hanging_protocol}" if hanging_protocol else ""
        series = f"&SeriesInstanceUIDs={series_uid}" if series_uid else ""
        page.goto(f"{viewer_url}/viewer?StudyInstanceUIDs={study_uid}{series}{protocol}#token={token}")
        deadline = time.monotonic() + timeout_s
        frames_served = 0
        wanted = min(3, len(pacs.by_study.get(study_uid, [])) or 3)  # a two-image radiograph loads two frames, not three
        if whole_series:  # a reconstruction is only complete once every slice of the volume has arrived
            wanted = sum(1 for sop in pacs.by_study.get(study_uid, []) if not series_uid or str(pacs.instances[sop][1].SeriesInstanceUID) == series_uid) or wanted
        while time.monotonic() < deadline:
            frames_served = sum(1 for r in pacs.requests if "/frames/" in r["path"])
            if frames_served >= wanted and page.locator("canvas").count() > 0:
                break
            time.sleep(1)
        time.sleep(settle_s)  # let the last frames paint (a volume takes longer than a stack)
        warnings_before = len(warnings)
        if orientation_change:
            # The viewport orientation menu of the first (active) viewport: pick an orientation another viewport already
            # has. Without the Crosshairs guard in app-config.js this sets every camera of the layout to NaN (black).
            page.locator('[data-cy="orientationMenu-btn"]').first.click(timeout=15000)
            page.get_by_text(orientation_change, exact=True).first.click(timeout=5000)
            time.sleep(3)
        cameras = page.evaluate(CAMERAS_JS)
        warnings_after_change = [w for w in warnings[warnings_before:] if "WebGL" in w]
        if screenshot:
            page.screenshot(path=screenshot)
        browser.close()

    unauthorized = [r for r in pacs.requests if not (r["authorization"] or "").startswith("Bearer ")]
    print(f"requests to the PACS: {len(pacs.requests)} · frames: {frames_served} · without a bearer token: {len(unauthorized)}")
    for r in pacs.requests:
        if r["path"].endswith("/studies"):
            print(f"  QIDO {r['path']}?{r['query'][:160]}")
    print(f"console errors: {len(errors)}")
    for e in errors[:10]:
        print(f"  - {e[:300]}")
    for f in failed[:10]:
        print(f"  failed request: {f[:200]}")
    degenerate = [c for c in cameras if not c["usable"]]
    if cameras:
        print(f"viewport cameras: {len(cameras)} · unusable (NaN, default or degenerate): {len(degenerate)}" + (f" · WebGL warnings after the orientation change to {orientation_change}: {len(warnings_after_change)} · orientations: " + ", ".join(str(c["orientation"]) for c in cameras) if orientation_change else ""))
        for w in warnings_after_change[:3]:
            print(f"  - {w[:200]}")
    ok = frames_served >= wanted and not any("ReferenceError" in e or "TypeError" in e for e in errors) and not unauthorized and not degenerate and not warnings_after_change
    print("viewer check:", "OK" if ok else "FAILED")
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seed", default=None, help="folder of generated DICOM (default: the staged .build/dicom-seed, generated if missing)")
    ap.add_argument("--viewer-port", type=int, default=8081)
    ap.add_argument("--pacs-port", type=int, default=8042)
    ap.add_argument("--check", action="store_true", help="drive headless Chromium through a study and report")
    ap.add_argument("--study", default="1.2.276.0.7230010.3.1.2.8323329.1001", help="StudyInstanceUID to open with --check")
    ap.add_argument("--screenshot", default=None, help="write a PNG of the viewer after loading (with --check)")
    ap.add_argument("--timeout", type=float, default=90.0)
    ap.add_argument("--hanging-protocol", default=None, help="OHIF layout to open with: mpr, fourUp (the panel's 3D), main3D, only3D, primaryAxial, mprAnd3DVolumeViewport (CT only)")
    ap.add_argument("--settle", type=float, default=2.0, help="seconds to wait after the frames arrived before the screenshot")
    ap.add_argument("--series", default=None, help="SeriesInstanceUID to open (OHIF's SeriesInstanceUIDs filter), e.g. the axial volume")
    ap.add_argument("--whole-series", action="store_true", help="with --check: wait for every frame of the series (the volume) before the screenshot, not just the first three")
    ap.add_argument("--orientation-change", default=None, metavar="Axial|Sagittal|Coronal", help="with --check and an MPR layout: give the first viewport this orientation through its menu and require every camera to stay finite (the Crosshairs guard)")
    args = ap.parse_args()

    seed_dir = Path(args.seed) if args.seed else Path(dicom_seed.stage_dicom_seed())
    pacs = FakePacs(seed_dir)
    dist = Path(stage_ohif())
    pacs_url = f"http://127.0.0.1:{args.pacs_port}/dicom-web"
    viewer_url = f"http://127.0.0.1:{args.viewer_port}"
    config = ohif_app_config(pacs_url, friendly_name="Local PACS over the generated seed")

    servers = [pacs_server(pacs, args.pacs_port), viewer_server(dist, config, args.viewer_port)]
    for s in servers:
        threading.Thread(target=s.serve_forever, daemon=True).start()
    print(f"PACS (DICOMweb): {pacs_url} · {len(pacs.instances)} instances in {len(pacs.by_study)} studies")
    print(f"viewer: {viewer_url}/viewer?StudyInstanceUIDs={args.study}#token=local-dev-token")

    try:
        if args.check:
            return check(viewer_url, args.study, "local-dev-token", pacs, args.screenshot, args.timeout, args.hanging_protocol, args.settle, args.series, args.whole_series, args.orientation_change)
        print("Ctrl-C to stop")
        while True:
            time.sleep(3600)
    except KeyboardInterrupt:
        return 0
    finally:
        for s in servers:
            s.shutdown()


if __name__ == "__main__":
    sys.exit(main())
